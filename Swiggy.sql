-- 12. What is the total revenue generated by top 1% restaurants

SELECT  SUM(rating_count*cost) from
(SELECT *, (RATING_COUNT*COST) AS REVENUE, ROW_NUMBER() 
OVER( ORDER BY (RATING_COUNT*COST) DESC) AS "RANK" FROM restaurants) AS T
WHERE T.RANK <= (SELECT ceil(COUNT(*)*0.01) FROM restaurants);


-- 13. What % of revenue is generated by top 20% of restaurants with respect to total revenue?

WITH
q1 as 
(SELECT SUM(rating_count*cost) as "top_revenue" FROM 
(SELECT rating_count,cost,(rating_count*cost) as revenue, ROW_NUMBER() 
OVER(ORDER BY rating_count*cost DESC) AS "RANK" FROM restaurants) AS T
WHERE T.RANK <= (SELECT ceil(COUNT(*)*0.20) FROM restaurants)),

q2 as 
(SELECT SUM(rating_count*cost) as 'total_revenue' FROM restaurants)

select round((top_revenue/total_revenue)*100) as " revenue %" from q1 , q2;


