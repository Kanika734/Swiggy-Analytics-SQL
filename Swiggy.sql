-- WINDOW FUNCTION

-- 1. Rank every restaurant from most expensive to least expensive

SELECT name,cost, RANK() OVER(ORDER BY COST DESC) as "RANK" FROM restaurants;


-- 2. Rank every restaurant from most visited to least visited

SELECT name,rating_count, RANK() OVER(ORDER BY RATING_COUNT DESC) as "RANK" FROM restaurants;


-- 3. Rank every restaurant from most expensive to least expensive as per their city

SELECT name,cost,city,RANK() OVER(PARTITION BY city ORDER BY COST DESC)as "RANK" FROM restaurants;


-- 4. Dense-rank every restaurant from most expensive to least expensive as per their city

SELECT name,cost,city, DENSE_RANK() OVER(PARTITION BY city ORDER BY cost DESC )as "DENSE_RANK" FROM restaurants;


-- 5 Rank the restaurant based on their prices (most to least exp) 
-- as per the cuisine(row_number,dense_rank,rank)

SELECT name,cost,cuisine, RANK() OVER( PARTITION BY cuisine ORDER BY (cost) DESC) as "RANK",
DENSE_RANK() OVER( PARTITION BY cuisine ORDER BY (cost) DESC) as "DENSE_RANK",
ROW_NUMBER() OVER( PARTITION BY cuisine ORDER BY (cost) DESC) as "ROW_NUMBER" FROM restaurants;


-- 6. Row-number every restaurant from most expensive to least expensive as per their city

SELECT name,cost,city, ROW_NUMBER() OVER(PARTITION BY city ORDER BY cost DESC) as "ROW_NUMBER" FROM restaurants;


-- 7. Rank every restaurant from most expensive to least expensive as per 
-- their city along with its city [Adilabad - 1, Adilabad - 2]

SELECT name,cost, CONCAT(CITY,"-",RANK() OVER(PARTITION BY city ORDER BY cost DESC)) AS "RANK" FROM restaurants;


